print("\n=== Problem 5(a): Certifier Design ===")

print("""
Certifier name: ZeroLower

Shape declaration:
ZeroLower uses the same abstract shape as DeepPoly.
The shape stores lower and upper bounds and
symbolic expressions for each neuron.

Affine transformer:
ZeroLower keeps the original DeepPoly Affine
transformer unchanged.

ReLU transformer:
ZeroLower keeps the original DeepPoly ReLU
transformer except for its lower-bound selection.

Original DeepPoly:
If the ReLU input crosses zero, DeepPoly chooses
between the input expression and zero using
the condition lower_bound + upper_bound >= 0.

ZeroLower:
If the ReLU input crosses zero, ZeroLower always
chooses zero as the lower bound.

Reason for modification:
Zero is always a valid lower bound for ReLU.
This simplifies the lower-bound selection,
although it may reduce verification precision.
""")
