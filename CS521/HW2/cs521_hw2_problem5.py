# CELL 7: HardTanh Transformer Implementation
#
# Purpose:
# Implement the HardTanh activation function and its
# abstract transformer using ConstraintFlow.
# Save the implementation as hardtanh.cf.
# ============================================================

from pathlib import Path

folder = Path("/content/CCS521FA26HW/hw2/q5")

original = (folder / "deeppoly.cf").read_text()

# HardTanh function: clamp x to [-1, 1]
functions = """
func hardtanh(Float x) =
    x <= (0.0 - 1.0) ? (0.0 - 1.0) : (x >= 1.0 ? 1.0 : x);
"""

# Insert function before transformer
marker = "transformer deeppoly{"
assert marker in original

modified = original.replace(
    marker, functions + "\n" + marker, 1
)

# Original ReLU transformer
old = (
    "Relu -> (relu(prev[l]), relu(prev[u]), "
    "relu_lower(prev), relu_upper(prev));"
)

# Add HardTanh transformer using constant
# polyhedral lower and upper bounds
new = (
    "Relu -> (relu(prev[l]), relu(prev[u]), "
    "relu_lower(prev), relu_upper(prev));\n"
    "    HardTanh -> (hardtanh(prev[l]), "
    "hardtanh(prev[u]), "
    "hardtanh(prev[l]), hardtanh(prev[u]));"
)

assert old in modified, "ReLU rule not found"

modified = modified.replace(old, new, 1)

output = folder / "hardtanh.cf"
output.write_text(modified)

print("Created:", output)
print("HardTanh transformer added successfully.")
print("CELL 7: FILE CREATED")

